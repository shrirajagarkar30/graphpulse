"""E1: budget sweep - measured competitive ratio versus the proven rho(c) (Milestone 7.3).

Single tree, oracle-F mode (the proofs hold for oracle F).  For each family,
update mode, seed and budget c we run `analysis.measure` and compare
    ratio = online_cost / OPT,   OPT = sum_t min(r_t, F_t) (+ equal certificate work)
with rho(c) = (1+c)/min(c,1).  Hard check (deterministic c in (0, inf)):
    ratio <= rho(c) + slack,   slack = 2*T/OPT   (the "+2" of the work bound, per update).
c = 0 and c = inf have rho = inf (limits) and are reported without a bound; the
randomized budget is reported without a hard single-run check (it is an
expectation; see tests/test_e1_bound.py for the averaged check).

Usage: python -m experiments.e1_budget [--quick] [--out DIR]
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

from experiments.common import RESULTS, write_csv, write_markdown
from graphpulse.analysis import measure
from graphpulse.generators import comb_adversarial, grid, hub_spoke, random_sparse, random_updates

C_VALUES = [0.0, 0.25, 0.5, 1.0, 2.0, math.inf, "random"]
COLUMNS = ["family", "mode", "seed", "c", "T_actual", "online_cost", "opt_cost", "ratio", "rho", "slack",
           "bound_ok", "fallback_rate", "n_cert", "n_alt", "n_repair", "n_fallback"]


def rho(c) -> float:
    if c == "random":
        return math.e / (math.e - 1.0)
    if c == 0 or math.isinf(c):
        return math.inf
    return max(1.0 + c, (1.0 + c) / c)


def families(quick: bool):
    if quick:
        return {"grid": lambda s: grid(8, 8, seed=s), "random_sparse": lambda s: random_sparse(60, 300, seed=s),
                "hub_spoke": lambda s: hub_spoke(4, 10, seed=s), "comb": lambda s: comb_adversarial(60)}
    return {"grid": lambda s: grid(30, 30, seed=s), "random_sparse": lambda s: random_sparse(1000, 5000, seed=s),
            "hub_spoke": lambda s: hub_spoke(10, 100, seed=s), "comb": lambda s: comb_adversarial(500)}


def run(quick: bool = False, out_dir: Path | None = None, seeds: list[int] | None = None) -> list[Path]:
    out_dir = out_dir or RESULTS
    seeds = seeds or ([0] if quick else [0, 1, 2])
    plan = [("uniform", 150 if quick else 2000), ("tree_edges", 60 if quick else 500)]
    rows: list[dict] = []
    for fam, make in families(quick).items():
        for mode, T in plan:
            for seed in seeds:
                g = make(seed)
                upds = random_updates(g, T, seed=seed, mode=mode, p_delete=0.02)
                for c in C_VALUES:
                    res = measure(g, upds, c=c, mode="oracle", src=0, seed=seed)
                    ratio = res.ratio
                    r = rho(c)
                    slack = 2.0 * res.updates_count / res.opt_cost if res.opt_cost else 0.0
                    ok = True if (c == "random" or math.isinf(r)) else (ratio <= r + slack)
                    if not ok:
                        raise AssertionError(f"measured ratio {ratio} exceeds rho={r} + slack={slack} "
                                             f"({fam}, {mode}, seed={seed}, c={c})")
                    sc = res.strategy_counts
                    rows.append({
                        "family": fam, "mode": mode, "seed": seed, "c": c, "T_actual": res.updates_count,
                        "online_cost": res.online_cost, "opt_cost": res.opt_cost, "ratio": round(ratio, 6),
                        "rho": r, "slack": round(slack, 6), "bound_ok": int(ok),
                        "fallback_rate": round(sc["fallback"] / max(1, res.updates_count), 6),
                        "n_cert": sc["cert"], "n_alt": sc["alt"], "n_repair": sc["repair"],
                        "n_fallback": sc["fallback"],
                    })
    csv_path = write_csv(rows, COLUMNS, out_dir / "e1_budget.csv")
    df = pd.DataFrame(rows)
    df["c"] = df["c"].astype(str)
    agg = (df.groupby(["family", "mode", "c"], sort=False)
             .agg(online_cost=("online_cost", "sum"), opt_cost=("opt_cost", "sum"),
                  mean_ratio=("ratio", "mean"), max_ratio=("ratio", "max"),
                  rho=("rho", "first"), fallback_rate=("fallback_rate", "mean"))
             .reset_index())
    summary = agg.to_dict("records")
    cols = ["family", "mode", "c", "online_cost", "opt_cost", "mean_ratio", "max_ratio", "rho", "fallback_rate"]
    for r in summary:
        r["mean_ratio"], r["max_ratio"] = round(r["mean_ratio"], 4), round(r["max_ratio"], 4)
        r["fallback_rate"] = round(r["fallback_rate"], 4)
        r["rho"] = float(r["rho"])
    md = write_markdown(summary, cols, out_dir / "e1_budget.md", "E1: measured competitive ratio vs proven rho(c)",
                        "Oracle-F mode, single tree (source 0). Seeds: " + ", ".join(map(str, seeds)) +
                        ". `rho` is infinite for c = 0 and c = inf. Generated by `experiments/e1_budget.py`; "
                        "per-seed rows in `e1_budget.csv`.")
    return [csv_path, md]


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args()
    for p in run(a.quick, a.out):
        print("wrote", p)
